import { createHash } from "node:crypto";

export const PROVIDER_MODEL_CATALOG_PATH = "packages/core/src/provider-model-catalog.generated.ts";
export const PROVIDER_MODEL_CATALOG_SOURCE = "https://models.dev/api.json";
export const TRUSTED_PROVIDER_IDS = Object.freeze([
  "alibaba",
  "anthropic",
  "deepseek",
  "google",
  "minimax",
  "mistral",
  "moonshotai",
  "openai",
  "siliconflow",
  "stepfun",
  "volcengine",
  "xai",
  "zai",
  "zhipuai",
]);

const header = "// Generated by scripts/sync-provider-model-catalog.mjs. Do not edit manually.\n"
  + 'import type { ProviderModelCatalogManifest, ProviderModelCatalogRecord } from "./provider-types.js";\n\n'
  + "export const providerModelCatalogManifest = ";
const separator = " as const satisfies ProviderModelCatalogManifest;\n\nexport const providerModelCatalogRecords = ";
const footer = " as const satisfies readonly ProviderModelCatalogRecord[];\n";

export function providerModelCatalogVersion(records) {
  return `models.dev:${createHash("sha256").update(JSON.stringify(records)).digest("hex").slice(0, 12)}`;
}

export function renderProviderModelCatalog({ generatedAt, records, updatedAt, version }) {
  const manifest = {
    schemaVersion: 1,
    version,
    source: "models.dev",
    sourceUrl: PROVIDER_MODEL_CATALOG_SOURCE,
    license: "MIT",
    generatedAt,
    updatedAt,
  };
  return header + JSON.stringify(manifest, null, 2) + separator + JSON.stringify(records, null, 2) + footer;
}

/** Verify the serialized data without importing the candidate TypeScript module. */
export function isGeneratedProviderModelCatalog(source) {
  if (!source.startsWith(header) || !source.endsWith(footer)) return false;
  const separatorAt = source.indexOf(separator, header.length);
  if (separatorAt < 0) return false;
  try {
    const manifest = JSON.parse(source.slice(header.length, separatorAt));
    const records = JSON.parse(source.slice(separatorAt + separator.length, -footer.length));
    if (manifest?.schemaVersion !== 1 || manifest.source !== "models.dev"
      || manifest.sourceUrl !== PROVIDER_MODEL_CATALOG_SOURCE || manifest.license !== "MIT"
      || typeof manifest.version !== "string" || !/^models\.dev:[0-9a-f]{12}$/u.test(manifest.version)
      || typeof manifest.generatedAt !== "string" || typeof manifest.updatedAt !== "string"
      || !Array.isArray(records) || records.length === 0 || !records.every(isGeneratedRecord)) return false;
    const keys = records.map(record => `${record.providerId}\u0000${record.id.toLowerCase()}`);
    if (new Set(keys).size !== keys.length) return false;
    return source === renderProviderModelCatalog({
      generatedAt: manifest.generatedAt,
      records,
      updatedAt: manifest.updatedAt,
      version: providerModelCatalogVersion(records),
    });
  } catch (error) {
    if (error instanceof SyntaxError) return false;
    throw error;
  }
}

function isGeneratedRecord(record) {
  return record !== null && typeof record === "object" && !Array.isArray(record)
    && TRUSTED_PROVIDER_IDS.includes(record.providerId)
    && typeof record.id === "string" && record.id.trim().length > 0
    && Array.isArray(record.capabilities)
    && record.capabilities.every(capability => typeof capability === "string");
}
